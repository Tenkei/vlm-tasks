"""Generate the comparison table and CSV solely from completed task reports."""
from __future__ import annotations

import argparse
import csv
from html import escape
import json
from pathlib import Path

from .common import DATASETS, digest, utc_now, write_json

METRICS = {
    "classify": [("accuracy_top1", "Top-1 accuracy")],
    "detect": [("precision", "P@.5"), ("recall", "R@.5"), ("f1", "F1@.5")],
    "ground_box": [("accuracy_iou_0.5", "Acc@.5"), ("accuracy_iou_0.75", "Acc@.75"),
                   ("accuracy_iou_0.9", "Acc@.9"), ("mean_iou", "Mean IoU")],
    "ground_point": [("point_in_box_accuracy", "Point in box")],
    "attributes": [("accuracy", "Accuracy"), ("mean_attribute_accuracy", "Mean accuracy"), ("macro_f1", "Macro F1")],
    "answer": [("vqa_accuracy", "VQA accuracy")],
    "describe": [("cider", "CIDEr"), ("bleu_1", "BLEU-1"), ("bleu_2", "BLEU-2"),
                 ("bleu_3", "BLEU-3"), ("bleu_4", "BLEU-4"), ("rouge_l", "ROUGE-L")],
}


def format_number(value, decimal_places):
    text = f"{value:.{decimal_places}f}"
    return text.rstrip("0").rstrip(".") if "." in text else text


def load_reports(directory):
    directory = Path(directory)
    reports = []
    for run in sorted(directory.iterdir()):
        if not run.is_dir() or not (run / "config.json").is_file():
            continue
        config = json.loads((run / "config.json").read_text())
        for task in config["tasks"]:
            path = run / f"{task}.json"
            if path.is_file():
                reports.append((path, json.loads(path.read_text())))
    order = {task: i for i, task in enumerate(DATASETS)}
    reports.sort(key=lambda item: (order[item[1]["task"]], item[1]["model"]))
    return reports


def summarize(directory):
    directory = Path(directory)
    reports = load_reports(directory)
    lines = [
        "# Model benchmark comparison", "",
        "Generated by `python -m benchmarks.summarize`. [Method](../docs/benchmark-method.md) · "
        "[Runner](run.py) · [CSV](results/comparison.csv)", "",
        "N is the number of evaluated samples, including failures. Tokens are means per sample, "
        "rounded to the nearest whole token. Estimated cost is USD per 1,000 samples "
        "(total cost divided by N × 1,000); failure and cap rates also use N. "
        "Mean latency is seconds per sample. "
        "This is a preliminary "
        "task comparison; datasets and metrics differ between tasks. Ratios are shown as percentages; "
        "caption scores use their native scale. Latency includes the first inference call and excludes "
        "model loading and dataset preparation. Token usage includes invalid generated responses. "
        "Local monetary cost is unmeasured; hosted USD costs are estimates, not invoices. "
        "Hosted latency includes network and service time. Hardware, provider preprocessing and "
        "tokenizers differ between backends. Failure rate displays the cap rate in parentheses; "
        "both use N, and a cap hit is not necessarily a failure. The cap rate counts responses using the full configured "
        "output allowance (4,096 tokens in this baseline); raw responses distinguish incomplete "
        "output from a response finishing exactly at the limit.", "",
        "| Model | Task / dataset | N | Validation metrics | Failure rate (at cap) | Input tokens / sample | Output tokens / sample | Estimated cost / 1,000 samples | Mean latency (s) |",
        "|---|---|---:|---|---:|---:|---:|---:|---:|",
    ]
    rows = []
    for path, report in reports:
        task, m, usage = report["task"], report["metrics"], report["usage"]
        config = json.loads((path.parent / "config.json").read_text())
        calls_path = path.with_suffix(".jsonl")
        at_cap = None
        if calls_path.is_file():
            calls = [json.loads(line) for line in calls_path.read_text().splitlines()]
            at_cap = sum(g["output_tokens"] >= config["max_new_tokens"]
                         for call in calls for g in call["generations"])
        scores = []
        for key, label in METRICS[task]:
            if key in m:
                value = format_number(m[key], 4) if task == "describe" else f"{format_number(100 * m[key], 2)}%"
                scores.append(f"{label} {value}")
        latency = report["speed_ms_per_sample"]["inference"] / 1000
        relative = path.relative_to(directory).as_posix()
        samples = m["samples"]
        failure_rate = m["failures"] / samples if samples else None
        cap_rate = at_cap / samples if at_cap is not None and samples else None
        input_per_sample = usage["input_tokens"] / samples if samples else None
        output_per_sample = usage["output_tokens"] / samples if samples else None
        cost = usage.get("estimated_cost_usd")
        cost_per_sample = float(cost) / samples if cost is not None and samples else None
        cost_per_1k_samples = cost_per_sample * 1000 if cost_per_sample is not None else None
        cost_text = format_number(cost_per_1k_samples, 3) if cost_per_1k_samples is not None else "—"
        if cost is not None and usage.get("estimated_cost_complete") is False:
            cost_text += " (partial)"
        failure_text = f"{format_number(100 * failure_rate, 2)}%" if failure_rate is not None else "—"
        cap_text = f"{format_number(100 * cap_rate, 2)}%" if cap_rate is not None else "unknown"
        input_text = f"{input_per_sample:,.0f}" if input_per_sample is not None else "—"
        output_text = f"{output_per_sample:,.0f}" if output_per_sample is not None else "—"
        lines.append(f"| {report['model']} | [{task} / {report['dataset']}](results/{relative}) | "
                     f"{samples} | {'; '.join(scores)} | {failure_text} ({cap_text}) | "
                     f"{input_text} | {output_text} | {cost_text} | {format_number(latency, 3)} |")
        row = {"run": path.parent.name, "model": report["model"], "revision": report["revision"],
               "task": task, "dataset": report["dataset"], "device": report["device"], "dtype": report["dtype"],
               "backend": report.get("backend", "transformers"), "region": report.get("region"),
               **m, **{f"usage_{k}": v for k, v in usage.items()},
               "failure_rate": failure_rate,
               "max_new_tokens": config["max_new_tokens"], "responses_at_token_cap": at_cap,
               "responses_at_token_cap_per_sample": cap_rate,
               "usage_input_tokens_per_sample": input_per_sample,
               "usage_output_tokens_per_sample": output_per_sample,
               "usage_estimated_cost_usd_per_sample": cost_per_sample,
               "usage_estimated_cost_usd_per_1k_samples": cost_per_1k_samples,
               "inference_seconds_per_sample": latency, "elapsed_seconds": report["elapsed_seconds"],
               "dataset_fingerprint_sha256": report["dataset_fingerprint_sha256"]}
        rows.append(row)
    lines += ["", "`ClassifyMultiLabel` has no built-in validation dataset and is excluded. Detection uses "
              "COCO128 training images, classification uses CIFAR-10 test (`val` alias), and OVAD uses its "
              "benchmark (`val` alias). Grounding, VQA and captions use their validation splits. "
              "See the method for subset and scoring limitations.", ""]
    report_hashes = {str(path.relative_to(directory)): digest(path.read_bytes()) for path, _ in reports}
    chart_manifest = directory / "charts" / "manifest.json"
    if chart_manifest.is_file():
        charts = json.loads(chart_manifest.read_text())
        if charts["reports_sha256"] == report_hashes:
            lines += [
                "## Task profiles", "",
                "Same axes and 0–100 scale (metrics × 100); higher is better. Failures included. "
                "Polygon area is not an overall score.", "",
                "Regenerate with `python -m benchmarks.plot`. "
                "[Metrics and method](../docs/benchmark-method.md#task-profile-charts)", "",
            ]
            lines += ["<table>"]
            for start in range(0, len(charts["models"]), 4):
                lines += ["  <tr>"]
                models = charts["models"][start:start + 4]
                for model in models:
                    image = escape(f"results/charts/{model['run']}.png", quote=True)
                    vector = escape(f"results/charts/{model['run']}.svg", quote=True)
                    alt = escape(f"Task profile for {model['model']}", quote=True)
                    lines += [
                        '    <td width="25%" align="center">',
                        f'      <a href="{image}"><img src="{image}" alt="{alt}" width="220"></a><br>',
                        f'      <a href="{image}">PNG</a> · <a href="{vector}">SVG</a>',
                        "    </td>",
                    ]
                lines += ['    <td width="25%"></td>'] * (4 - len(models))
                lines += ["  </tr>"]
            lines += ["</table>"]
            lines += [""]
    directory.mkdir(parents=True, exist_ok=True)
    (directory.parent / "README.md").write_text("\n".join(lines))
    write_json(directory / "postprocessing.json", {
        "generated_at": utc_now(),
        "summarizer_sha256": digest(Path(__file__).read_bytes()),
        "reports_sha256": report_hashes,
    })
    fields = list(dict.fromkeys(key for row in rows for key in row))
    if rows:
        with (directory / "comparison.csv").open("w", newline="") as stream:
            writer = csv.DictWriter(stream, fieldnames=fields)
            writer.writeheader()
            writer.writerows(rows)
    return rows


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results", type=Path, default=Path("benchmarks/results"))
    summarize(parser.parse_args().results)
